import { wireBackupImport } from '../docs/js/backup-import.js';
import * as history from '../docs/js/history.js';
let pass=0,fail=0;
const check=(label,ok)=>{if(ok)pass++;else{fail++;console.log('FAIL:',label)}};
const store=new Map();globalThis.localStorage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
const events={};let clicked=0;
const input={files:[],value:'selected',click(){clicked++},addEventListener:(name,fn)=>events['input:'+name]=fn};
const button={textContent:'Import',disabled:false,addEventListener:(name,fn)=>events['button:'+name]=fn};
const feedback=[],order=[];
wireBackupImport(input,button,{importData:history.importData,feedback:(...args)=>{feedback.push(args);order.push(args[0]);},onImported:()=>order.push('redraw')});
events['button:click']();check('Import opens the hidden picker',clicked===1);
let read;input.files=[{text:()=>new Promise(resolve=>read=resolve)}];
const importing=events['input:change']();
check('selected backup shows visible busy state',button.disabled&&button.textContent==='Importing…'&&feedback.at(-1)[0].includes('Importing'));
const payload={format:'deepdive-backup',version:1,data:{deepdive_watchlist:JSON.stringify([{id:'1',name:'Artist'}])}};
read(JSON.stringify(payload));await importing;
check('backup is actually imported',JSON.parse(store.get('deepdive_watchlist')).length===1);
check('success reports added counts',feedback.at(-1)[0].includes('Added 1 pin,')&&feedback.at(-1)[2]===true);
check('success feedback happens after any redraw',order.at(-2)==='redraw'&&order.at(-1).startsWith('Backup imported'));
check('picker and button reset for another import',input.value===''&&!button.disabled&&button.textContent==='Import');
input.files=[{text:async()=>JSON.stringify(payload)}];await events['input:change']();
check('duplicate backup explicitly reports no new items',feedback.at(-1)[0]==='Backup imported. No new items to add.');
input.files=[{text:async()=>'{invalid'}];await events['input:change']();
check('invalid JSON is shown as an error',feedback.at(-1)[1]===true&&feedback.at(-1)[2]===true);
check('failure restores the Import button',!button.disabled&&input.value==='');
input.files=[];const count=feedback.length;await events['input:change']();
check('cancelling the file picker does not claim success',feedback.length===count);
console.log(`\n${pass} passed, ${fail} failed`);process.exit(fail?1:0);
