import { LibraryCache } from '../docs/js/library-cache.js';
import { progressArtwork } from '../docs/js/progress-artwork.js';
import { readFileSync } from 'node:fs';
let pass=0,fail=0;
const check=(label,ok)=>{if(ok)pass++;else{fail++;console.log('FAIL:',label)}};
const tick=()=>new Promise(resolve=>setImmediate(resolve));
const item=n=>({added_at:'2026-10-28',track:{id:String(n),name:'Song '+n,artists:[{id:'artist',name:'Artist'}],album:{images:[{url:'cover-'+n,width:640}]}}});
const data=new Map();let saves=0,calls=0,first,second;
const cache=new LibraryCache({get:async path=>{calls++;return new Promise(resolve=>{if(path==='me/tracks')first=resolve;else second=resolve;});}},
 {get:async key=>data.get(key),set:async(key,value)=>{data.set(key,value);saves++;}});
const progress1=[],progress2=[],progress3=[],art=[];
const p1=cache.getLikedTracks({onProgress:(...p)=>progress1.push(p),onArtwork:url=>art.push(url)});
const p2=cache.getLikedTracks({forceFull:true,onProgress:(...p)=>progress2.push(p)});
await tick();check('concurrent callers share the first page request',calls===1);
first({items:[item(1),item(2)],total:4,next:'page2'});await tick();
check('both views receive the same live page count',progress1[0]?.join('/')==='2/4'&&progress2[0]?.join('/')==='2/4');
const p3=cache.getLikedTracks({onProgress:(...p)=>progress3.push(p)});
check('joining after a tab redraw starts at current progress, not zero',progress3[0]?.join('/')==='2/4');
second({items:[item(3),item(4)],total:4,next:null});
const results=await Promise.all([p1,p2,p3]);
check('one paging loop serves all callers',calls===2&&results.every(r=>r.length===4));
check('shared scan saves the complete cache once',saves===1);
check('first sync supplies artwork from the pages already fetched',art.length===4&&art.includes('cover-1'));
const before=data.get('deepdive_library_v1');const abort=new AbortController();let cancelCalls=0;
cache.client.get=async()=>{cancelCalls++;return {items:[item(5)],total:2,next:'not-read'};};
let cancelled=false;try{await cache.getLikedTracks({forceFull:true,signal:abort.signal,onProgress:()=>abort.abort()});}catch(e){cancelled=e.name==='AbortError';}
check('cancel stops before requesting another page',cancelled&&cancelCalls===1);
check('cancelled partial read cannot replace the last complete cache',data.get('deepdive_library_v1')===before&&saves===1);
cache.client.get=async()=>({items:[item(8)],total:1,next:null});
check('a new read works after cancellation',(await cache.getLikedTracks({forceFull:true}))[0].id==='8');
let artCalls=0;cache.client.get=async()=>({items:Array.from({length:30},(_,i)=>item(i)),total:30,next:null});
await cache.getLikedTracks({forceFull:true,onArtwork:()=>artCalls++});
check('decoration downloads are bounded for very large libraries',artCalls===12);
const selected=progressArtwork([{album:{images:[{url:'small',width:160},{url:'large',width:640}]}}],
 [{image_url_large:'artist-photo'},{image_url:'tiny-pin'}],{random:()=>0});
check('artist photos lead the fallback artwork pool',selected[0]==='artist-photo');
check('album artwork uses the largest available source',selected.includes('large')&&!selected.includes('small'));
check('small pin thumbnails are not stretched into full-screen backgrounds',!selected.includes('tiny-pin'));
check('fallback image pool is deduplicated and bounded',progressArtwork(Array.from({length:30},(_,i)=>item(i).track),[],{limit:12}).length===12);
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const app=read('docs/js/app.js');
check('explicit reads use the full-screen job',/showDiveScreen\("Reading your library/.test(app));
check('the screen and cache share one notification lease',/backgroundLease: job.screen/.test(app));
check('tab changes cannot replace an active library read',/if \(_libraryRead && !_libraryRead.controller.signal.aborted\) return;\s*const name = tab.dataset.tab/.test(app));
check('old cancelled scan cannot close a newer progress screen',/if \(_diveBackground === job.screen\) hideDiveScreen\(\)/.test(app));
const css=read('docs/app/index.html');
const wraps=[...css.matchAll(/\.wrap\s*\{([^}]*)\}/g)].map(m=>m[1]);
const phone=wraps.filter(rule=>/padding:0 16px/.test(rule)).at(-1);
check('the last phone padding rule still clears the floating bar',phone?.includes('var(--tabbar-height, 80px) + 32px'));
check('tab bar height is measured rather than assuming a fixed font size',/setProperty\("--tabbar-height", `\$\{barBox.height\}px`\)/.test(app));
console.log(`\n${pass} passed, ${fail} failed`);process.exit(fail?1:0);
